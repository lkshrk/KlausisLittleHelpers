#!/usr/bin/env python3
"""Usage: scripts/taxi-data.py <build> <csv-dir>

Writes Data/TaxiPaths.lua from TaxiNodes.csv, TaxiPath.csv and TaxiPathNode.csv in <csv-dir>,
the wago.tools exports of that build (https://wago.tools/db2/<Table>/csv?build=<build>).
"""
import csv
import math
import sys
from collections import defaultdict
from pathlib import Path

TELEPORT = 0x1
TOLERANCE = 30
FACTION_RADIUS = 600
SIDES = {1: "A", 2: "H"}


def simplify(points):
    if len(points) < 3:
        return points
    (ax, ay), (bx, by) = points[0], points[-1]
    dx, dy = bx - ax, by - ay
    norm = math.hypot(dx, dy) or 1.0
    far, index = 0.0, 0
    for i in range(1, len(points) - 1):
        px, py = points[i]
        d = abs(dy * (px - ax) - dx * (py - ay)) / norm if (dx or dy) else math.hypot(px - ax, py - ay)
        if d > far:
            far, index = d, i
    if far <= TOLERANCE:
        return [points[0], points[-1]]
    return simplify(points[: index + 1])[:-1] + simplify(points[index:])


def length(a, b):
    return math.dist([float(a[f"Loc_{i}"]) for i in range(3)], [float(b[f"Loc_{i}"]) for i in range(3)])


def dock_side(dock, masters):
    sides = {
        flags & 3 for c, x, y, flags in masters
        if c == int(dock["ContinentID"]) and math.hypot(x - float(dock["Loc_0"]), y - float(dock["Loc_1"])) < FACTION_RADIUS
    }
    return SIDES.get(sides.pop()) if len(sides) == 1 else None


def merge_close(stops, legs):
    stops, legs = list(stops), list(legs)
    k = 1
    while k <= len(stops) and len(stops) > 1:
        idx = k % len(stops)
        here, prev = stops[idx], stops[k - 1]
        if math.hypot(float(here["Loc_0"]) - float(prev["Loc_0"]), float(here["Loc_1"]) - float(prev["Loc_1"])) < 50:
            legs[k - 1] += legs[idx]
            del stops[idx]
            del legs[idx]
        else:
            k += 1
    return stops, legs


def transports(points):
    result = []
    for nodes in points.values():
        nodes = sorted(nodes, key=lambda n: int(n["NodeIndex"]))
        docks = [i for i, n in enumerate(nodes) if int(n["Delay"]) > 0]
        if len(docks) < 2:
            continue
        step = [0.0] * len(nodes)
        for i in range(1, len(nodes)):
            prev, cur = nodes[i - 1], nodes[i]
            jump = int(prev["Flags"]) & TELEPORT or prev["ContinentID"] != cur["ContinentID"]
            step[i] = 0.0 if jump else length(prev, cur)
        total = sum(step)
        legs = []
        for k, start in enumerate(docks):
            end = docks[(k + 1) % len(docks)]
            yards = sum(step[start + 1:end + 1]) if end > start else total - sum(step[end + 1:start + 1])
            legs.append(round(yards))
        stops, legs = merge_close([nodes[i] for i in docks], legs)
        if len(stops) < 2:
            continue
        result.append((stops, legs, sum(int(n["Delay"]) for n in nodes)))
    return result


def table(folder, name):
    with open(Path(folder) / f"{name}.csv", newline="", encoding="utf-8") as f:
        return list(csv.DictReader(f))


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    build, folder = sys.argv[1], sys.argv[2]
    taxi_nodes = table(folder, "TaxiNodes")
    continent = {int(r["ID"]): int(r["ContinentID"]) for r in taxi_nodes}
    masters = [
        (int(r["ContinentID"]), float(r["Pos_0"]), float(r["Pos_1"]), int(r["Flags"])) for r in taxi_nodes
        if not r["Name_lang"].startswith(("Transport", "Generic", "Quest Path"))
    ]
    points = defaultdict(list)
    for r in table(folder, "TaxiPathNode"):
        points[int(r["PathID"])].append(r)

    edges = defaultdict(dict)
    for r in table(folder, "TaxiPath"):
        a, b, path = int(r["FromTaxiNode"]), int(r["ToTaxiNode"]), int(r["ID"])
        if a == b or a not in continent or continent.get(a) != continent.get(b) or not points[path]:
            continue
        nodes = sorted(points[path], key=lambda n: int(n["NodeIndex"]))
        length, delay = 0.0, 0
        curve = simplify([
            (float(n["Loc_1"]), float(n["Loc_0"])) for n in nodes
            if not int(n["Flags"]) & TELEPORT and int(n["ContinentID"]) == continent[a]
        ])
        for prev, cur in zip(nodes, nodes[1:]):
            delay += int(prev["Delay"])
            if int(prev["Flags"]) & TELEPORT or prev["ContinentID"] != cur["ContinentID"]:
                continue
            length += math.dist(
                [float(prev[f"Loc_{i}"]) for i in range(3)],
                [float(cur[f"Loc_{i}"]) for i in range(3)],
            )
        edges[a][b] = (round(length), delay, ", ".join(f"{round(x)}, {round(y)}" for x, y in curve))

    out = [
        "local _, ns = ...",
        "if ns.IS_FOREVER == false then return end",
        "",
        f"-- Generated by scripts/taxi-data.py from build {build}: [from][to] = {{ yards, stop seconds, {{ HBD world x1, y1, ... }} }}",
        "ns.TaxiPaths = {",
    ]
    for a in sorted(edges):
        out.append(f"    [{a}] = {{")
        for b, (length, delay, curve) in sorted(edges[a].items()):
            out.append(f"        [{b}] = {{ {length}, {delay}, {{ {curve} }} }},")
        out.append("    },")
    out.append("}")
    out += [
        "",
        "-- Ships and zeppelins: docks { instance, x, y, side? }, yards to the next dock, seconds stopped per loop",
        "ns.Transports = {",
    ]
    ferries = 0
    for stops, legs, stop_seconds in transports(points):
        docks = []
        for n in stops:
            side = dock_side(n, masters)
            docks.append(
                f'{{ {n["ContinentID"]}, {round(float(n["Loc_1"]))}, {round(float(n["Loc_0"]))}'
                + (f', "{side}"' if side else "") + " }"
            )
        out.append(f"    {{ docks = {{ {', '.join(docks)} }}, legs = {{ {', '.join(map(str, legs))} }}, stops = {stop_seconds} }},")
        ferries += 1
    out.append("}")
    target = Path(__file__).resolve().parent.parent / "Data" / "TaxiPaths.lua"
    target.parent.mkdir(exist_ok=True)
    target.write_text("\n".join(out) + "\n", encoding="ascii")
    print(f"{target}: {sum(len(v) for v in edges.values())} paths from {len(edges)} nodes, {ferries} transports")


if __name__ == "__main__":
    main()
